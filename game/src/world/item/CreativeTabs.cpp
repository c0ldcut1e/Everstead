const ItemInstance &CreativeTabs::GetIcon(int tab)
{
    static std::vector<ItemInstance> icons;
    if (icons.empty())
    {
        icons.resize(s_tabCount);
        icons[0]              = ItemInstance(Item::ByName("stone_bricks"), 1);
        icons[1]              = ItemInstance(Item::ByName("grass_block"), 1);
        icons[2]              = ItemInstance(Item::ByName("stick"), 1);
        icons[3]              = ItemInstance(Item::ByName("red_wool"), 1);
        icons[4]              = ItemInstance(Item::ByName("iron_axe"), 1);
        icons[s_allItemsTab]  = ItemInstance(Item::ByName("compass"), 1);
        icons[s_inventoryTab] = ItemInstance(Item::ByName("crafting_table"), 1);
    }

    return icons[(size_t) tab];
}

const ItemInstance *CreativeTabs::GetItem(int tab, int index)
{
    if (tab < 0 || tab >= s_tabCount)
    {
        return nullptr;
    }

    const std::vector<ItemInstance> &items = GetItems(tab);
    return index >= 0 && index < (int) items.size() ? &items[(size_t) index] : nullptr;
}

std::string CreativeTabs::GetNameKey(int tab)
{
    if (tab == 0)
    {
        return "itemGroup.buildingBlocks";
    }

    if (tab == 1)
    {
        return "itemGroup.naturalBlocks";
    }

    if (tab == 2)
    {
        return "itemGroup.ingredients";
    }

    if (tab == 3)
    {
        return "itemGroup.coloredBlocks";
    }

    if (tab == 4)
    {
        return "itemGroup.tools";
    }

    if (tab == s_allItemsTab)
    {
        return "itemGroup.search";
    }

    if (tab == s_inventoryTab)
    {
        return "itemGroup.inventory";
    }

    return "";
}
